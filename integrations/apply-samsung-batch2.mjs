import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';

const root = path.resolve(process.cwd());
const site = path.join(root, 'site');
const evidence = JSON.parse(fs.readFileSync(path.join(root, 'integrations/samsung-optional-batch2-2026-10-08.json'), 'utf8'));
assert.equal(evidence.models.length, 4);
const packPath = path.join(site,'src/data/samsung-pack.js');
const indexPath = path.join(site,'src/data/new-brands-index.js');
const packSource = fs.readFileSync(packPath,'utf8');
const prefix = 'export const brandPack=';
const start = packSource.indexOf(prefix);
assert.ok(start > 0);
const brandPack = JSON.parse(packSource.slice(start+prefix.length).trim().replace(/;\s*$/, ''));
const indexSource = fs.readFileSync(indexPath,'utf8');
const idxPrefix = 'export const newBrandsIndex=';
const manifestPrefix = '\nexport const newBrandsManifest=';
const split = indexSource.indexOf(manifestPrefix);
assert.ok(indexSource.includes(idxPrefix) && split>0);
const modelIndex = JSON.parse(indexSource.slice(indexSource.indexOf(idxPrefix)+idxPrefix.length,split).replace(/;\s*$/,''));
const manifest = JSON.parse(indexSource.slice(split+manifestPrefix.length).trim().replace(/;\s*$/, ''));
assert.equal(brandPack.models.length, 66);
assert.equal(brandPack.parts.length, 34);
assert.equal(modelIndex.filter(x=>x.brand==='Samsung').length,66);
const byModel = new Map(brandPack.models.map(m=>[m.code,m]));
const byPart = new Map(brandPack.parts.map(p=>[p.code,p]));
let relations=0;
for(const item of evidence.models){
  const full = item.model;
  const code = full.split('/')[0];
  const model = byModel.get(code);
  assert.ok(model, 'Model not in catalogue: '+code);
  assert.deepEqual(model.deviceReferences, [full], 'Country/variant mismatch for '+code);
  assert.ok(!model.partCount, 'No duplicate or pre-existing model part list allowed: '+code);
  assert.equal(item.codes.length, new Set(item.codes).size);
  assert.equal(item.url.startsWith('https://www.samsung.com/de/vacuum-cleaners/stick/'),true);
  assert.ok(item.url.endsWith(code.toLowerCase()+'-wd/'));
  model.url = item.url;
  model.guideUrl = item.url;
  model.partsUrl = item.url;
  model.checkedAt = evidence.checked;
  model.sourceNote = 'Die deutsche Samsung-Produktseite nennt für den vollständigen Modellcode optionale Zubehörartikel. Dies ist weder eine vollständige Teileliste noch eine technische Freigabe; Preise und Verfügbarkeit sind nicht bestätigt.';
  model.partCount = item.codes.length;
  model.physicalPartCount = item.codes.length;
  model.partListCoverage = { sourceUrl:item.url, note: item.codes.length+' vom Hersteller ausdrücklich als optional gelistete Zubehörartikel erfasst. Die Geräte-/Artikelkennung und Zubehörbedingungen vor dem Kauf am eigenen Gerät prüfen; eine pauschale Passungsfreigabe ist damit nicht verbunden.' };
  for(const partCode of item.codes){
    const part = byPart.get(partCode);
    assert.ok(part,'Cannot invent or silently alias manufacturer SKU '+partCode);
    assert.ok(!part.relationships?.some(r=>r.reference===full), 'Existing relationship must not be duplicated: '+partCode+' '+full);
    part.relationships ??= [];
    part.relationships.push({code,model:code,reference:full,url:item.url,checkedAt:evidence.checked,basis:'manufacturer-device-optional-accessories'});
    part.sourceCoverage ??= {status:'partial',observedReferences:[]};
    const refs = [...new Set(part.relationships.map(r=>r.reference).filter(Boolean))];
    part.sourceCoverage.observedReferences=refs;
    part.sourceCoverage.note='Samsung nennt '+partCode+' ausdrücklich in der optionalen Zubehörliste für '+refs.join(', ')+'. Artikelvariante, Anschlüsse, Modell-Ländercode und zusätzliches Zubehör prüfen; keine automatische technische Freigabe.';
    if(['VCA-SPA75E/GL','VCA-SPW75E/VT','VCA-SPA95/GL','VCA-SPW95/VT'].includes(partCode)) assert.ok(part.attachmentReferences?.length,'Missing required wipe attachment');
    relations++;
  }
  const summary = modelIndex.find(m=>m.brand==='Samsung'&&m.code===code);
  assert.ok(summary,'Missing lightweight model '+code);
  summary.url=model.url;summary.guideUrl=model.guideUrl;summary.partsUrl=model.partsUrl;
  summary.checkedAt=evidence.checked;summary.sourceNote=model.sourceNote;
  summary.partCount=model.partCount;summary.physicalPartCount=model.physicalPartCount;
}
assert.equal(relations,35);
assert.equal(manifest.Samsung.partCount,34);
assert.equal(manifest.Samsung.physicalPartCount,34);
manifest.Samsung.note = '66 belegte Samsung-Gerätereferenzen und 34 verschiedene physische Zubehör-/Ersatzteilartikel. 13 /WD-Modelle haben je eine explizite Herstellerliste optionaler Zubehörkennungen; 53 Modelle sind noch ohne Teilezuordnung. Zubehörbedingungen, Preise, Bestände und exakte Passung bleiben prüfpflichtig.';
fs.writeFileSync(packPath, '// Source-linked manufacturer model references and articles, checked '+evidence.checked+'.\nexport const brandPack='+JSON.stringify(brandPack)+';\n');
fs.writeFileSync(indexPath, '// Manufacturer model references and lightweight catalogue coverage for Samsung and Hoover.\nexport const newBrandsIndex='+JSON.stringify(modelIndex)+';\nexport const newBrandsManifest='+JSON.stringify(manifest)+';\n');
console.log(JSON.stringify({changedModels:evidence.models.map(m=>m.model),newRelationships:relations,articleCodes:brandPack.parts.length,totalModels:brandPack.models.length,samsungUnassigned:brandPack.models.filter(m=>!m.partCount).length}));

// Hash the local UI and its existing shared modules. Writes only this directory.
import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
const here=path.dirname(fileURLToPath(import.meta.url));
const repo=path.resolve(here,'../..');
const sha=bytes=>createHash('sha256').update(bytes).digest('hex');
export const assetFiles=Object.freeze({
 '/':'index.html','/index.html':'index.html','/styles.css':'styles.css',
 '/app.mjs':'app.mjs','/mission-state.mjs':'mission-state.mjs',
 '/parts-view.mjs':'parts-view.mjs','/catalog-snapshot.mjs':'catalog-snapshot.mjs',
 '/mobile-ui.mjs':'mobile-ui.mjs',
 '/mock-fitment-adapter.mjs':'mock-fitment-adapter.mjs',
 '/manifest.webmanifest':'manifest.webmanifest','/app-icon.svg':'app-icon.svg',
 '/dual-platform-owner-review/bridge.mjs':'../dual-platform-owner-review/bridge.mjs',
 '/dual-platform-owner-review/ui-fixtures.mjs':'../dual-platform-owner-review/ui-fixtures.mjs',
 '/fitment-engine-v1-poc/contract.mjs':'../fitment-engine-v1-poc/contract.mjs',
 '/fitment-engine-v1-poc/fixtures.mjs':'../fitment-engine-v1-poc/fixtures.mjs',
 '/business-embed-poc/adapter.mjs':'../business-embed-poc/adapter.mjs'
});
export function offlineConfig(){
 const hashes=Object.fromEntries(Object.entries(assetFiles).map(([url,file])=>[url,sha(fs.readFileSync(path.resolve(here,file)))]));
 const policyHashes=['offline-worker.mjs','serve.mjs'].map(file=>sha(fs.readFileSync(path.join(here,file))));
 const cacheName='uf-consumer-mobile-wave4-'+sha(JSON.stringify([hashes,policyHashes])).slice(0,24);
 const catalogFingerprint=sha(JSON.stringify([
  hashes['/catalog-snapshot.mjs'],hashes['/fitment-engine-v1-poc/contract.mjs'],
  hashes['/fitment-engine-v1-poc/fixtures.mjs'],hashes['/dual-platform-owner-review/bridge.mjs'],
  hashes['/dual-platform-owner-review/ui-fixtures.mjs'],hashes['/business-embed-poc/adapter.mjs'],
  hashes['/mock-fitment-adapter.mjs']
 ]))+':consumer-ui/2';
 return {cacheName,catalogFingerprint,assetPaths:[...Object.keys(assetFiles),'/offline-config.mjs'],hashes};
}
export function configSource(){
 const c=offlineConfig();
 return '// Generated by prepare-offline.mjs; local identities and shared core stay unchanged.\n'+
  'export const cacheName='+JSON.stringify(c.cacheName)+';\n'+
  'export const catalogFingerprint='+JSON.stringify(c.catalogFingerprint)+';\n'+
  'export const assetPaths='+JSON.stringify(c.assetPaths,null,2)+';\n';
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)){
 const check=process.argv.includes('--check');
 if(!check)assert.equal(execFileSync('git',['branch','--show-current'],{cwd:repo,encoding:'utf8'}).trim(),'work/consumer-mobile-ux-wave4');
 const expected=configSource(),file=path.join(here,'offline-config.mjs');
 if(check)assert.equal(fs.readFileSync(file,'utf8'),expected,'Offline assets changed: regenerate the local config');
 else fs.writeFileSync(file,expected);
 const c=offlineConfig();
 console.log(JSON.stringify({offlineAssets:c.assetPaths.length,cacheName:c.cacheName,state:check?'byte-identical':'generated'}));
}

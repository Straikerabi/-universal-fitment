import assert from 'node:assert/strict';
import { products } from '../src/data/catalog.js';
import { cartQuoteItem } from '../src/data/miele-commerce.js';
import { marketplaceSearchNote } from '../src/core/marketplaces.js';
import { buildHandoffPlan, handoffListText, safeHandoffUrl } from '../src/core/handoff.js';

const NOW=Date.parse('2026-10-06T18:00:00Z');
const hx2=products.find(p=>p.id==='vac-miele-model-11806000');
const brush=hx2.parts.find(p=>p.id==='miele-part-11936221');
const battery=hx2.parts.find(p=>p.id==='aftermarket-vhbw-889005195');
const resolvePart=item=>products.find(p=>p.id===item.productId)?.parts.find(p=>p.id===item.partId)||null;
const quote={...cartQuoteItem(brush,hx2,NOW),quantity:2};
const note={...marketplaceSearchNote(battery,hx2,'used'),quantity:1};
const original=JSON.stringify([quote,note]);
let plan=buildHandoffPlan([quote,note],{resolvePart,now:NOW});
assert.equal(plan.mode,'merchant-links');assert.equal(plan.paymentLocation,'merchant');
assert.equal(plan.automaticCartTransfer,false);assert.equal(plan.createsOrder,false);assert.equal(plan.acceptsPayment,false);
assert.equal(plan.itemCount,2);assert.equal(plan.unitCount,3);assert.equal(plan.linkedCount,2);assert.equal(plan.searchCount,1);
assert.equal(plan.knownSubtotal,60.30);assert.equal(plan.total,null,'a search note keeps the overall total open');
assert.equal(plan.groups[0].total,60.30,'the existing merchant shipping threshold is retained');
const line=plan.groups[0].lines[0];
assert.equal(line.kind,'product-page');assert.equal(line.quantity,2);assert.equal(line.partNumber,'11936221');
assert.ok(line.links[0].url.includes('/product/11936221/'));
assert.equal(new URL(line.links[0].url).searchParams.has('quantity'),false,'do not claim quantity transfer by inventing shop parameters');
const search=plan.groups[1].lines[0];
assert.equal(search.kind,'marketplace-search');assert.equal(search.priceKnown,false);assert.equal(search.price,null);
assert.equal(search.requestedCondition,'Gebraucht');assert.equal(search.links.length,2);
for(const line of plan.groups.flatMap(g=>g.lines)){
  assert.equal(line.canTransferAutomatically,false);assert.equal(line.quantityTransferred,false);
  assert.equal(line.orderCreated,false);assert.equal(line.paymentAccepted,false);
}
assert.equal(JSON.stringify([quote,note]),original,'building a handoff does not alter or clear the saved cart');
const text=handoffListText(plan);
assert.ok(text.includes(`2 × ${brush.name}`));assert.ok(text.includes('Teilenummer: 11936221'));
assert.ok(text.includes('Gesucht: Gebraucht'));assert.ok(text.includes('eBay Suche:'));assert.ok(text.includes('Amazon Suche:'));
assert.ok(text.includes('kein Bestellauftrag'));assert.ok(text.includes('Mengen wurden nicht übertragen'));

plan=buildHandoffPlan([quote],{resolvePart,now:NOW});assert.equal(plan.total,60.30);
const secondQuote=cartQuoteItem(battery,hx2,NOW);
plan=buildHandoffPlan([quote,secondQuote],{resolvePart,now:NOW});
assert.equal(plan.groups.length,2);assert.equal(plan.total,140.29,'separate merchants remain separate purchases');
plan=buildHandoffPlan([{...quote,checkedAt:'2026-10-01T12:00:00Z'}],{resolvePart,now:NOW});
assert.equal(plan.total,null);assert.equal(plan.groups[0].lines[0].priceKnown,false);
assert.equal(plan.groups[0].lines[0].links.length,1,'old prices still have a page for checking the current price');
plan=buildHandoffPlan([{productId:hx2.id,partId:brush.id,label:brush.name,quantity:3,price:null}],{resolvePart,now:NOW});
assert.equal(plan.groups[0].lines[0].kind,'part-reference');assert.equal(plan.groups[0].lines[0].priceKnown,false);
assert.ok(plan.groups[0].lines[0].links[0].url.includes('/product/11936221/'));
assert.equal(plan.total,null,'a linked reference page does not choose a purchasable offer');
plan=buildHandoffPlan([{...note,sourceUrl:quote.sourceUrl,price:20}],{resolvePart,now:NOW});
assert.equal(plan.groups[0].lines[0].kind,'marketplace-search');assert.equal(plan.groups[0].lines[0].links.length,2,'searches cannot silently become shop offers');
const unknown={key:'unknown',label:'Unbekanntes Teil',quantity:1,sourceUrl:'javascript:alert(1)'};
plan=buildHandoffPlan([unknown],{resolvePart,now:NOW});
assert.equal(plan.unresolvedCount,1);assert.equal(plan.groups[0].lines[0].kind,'unresolved');
assert.ok(handoffListText(plan).includes('Anbieter/Angebot noch auswählen'));
for(const url of ['javascript:alert(1)','http://example.test/a','data:text/html,abc','https://user:secret@example.test/a','not a url'])assert.equal(safeHandoffUrl(url),null);
plan=buildHandoffPlan([{...note,lookupLinks:[{provider:'ebay',url:'https://www.ebay.de.evil.example/sch/i.html'}]}],{resolvePart,now:NOW});
assert.equal(plan.groups[0].lines[0].links.length,2,'an invalid stored search falls back to the known part query');
plan=buildHandoffPlan([{...unknown,fitmentStatus:'variant_check_required',quantity:-4}],{now:NOW});
assert.equal(plan.unitCount,1);assert.equal(plan.groups[0].lines[0].needsVariantCheck,true);
assert.ok(handoffListText(plan).includes('Ausführung und Anschlüsse'));
assert.equal(buildHandoffPlan(null).itemCount,0);assert.equal(buildHandoffPlan([]).total,null);
console.log('Handoff checks passed: exact part links, search/reference distinction, quantities and copied list, separate merchants, source-price age, open totals, safe URLs and no cart transfer/payment/order side effects.');

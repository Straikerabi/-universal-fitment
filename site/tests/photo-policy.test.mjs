import assert from 'node:assert/strict';
import fs from 'node:fs';
import {photoPolicy} from '../src/core/photo-policy.js';
import {normalizePreferences} from '../src/core/preferences.js';
assert.equal(photoPolicy().automatic,false);
assert.equal(photoPolicy('details',true).automatic,true);
assert.equal(photoPolicy('on-demand',true).automatic,false);
assert.equal(photoPolicy('on-demand',false).automatic,false);
assert.equal(photoPolicy('automatic',false).automatic,true);
assert.equal(photoPolicy('unexpected').mode,'details');
assert.equal(normalizePreferences({photos:'on-demand'}).photos,'on-demand');
assert.equal(normalizePreferences({photos:'injected'}).photos,'details');
const app=fs.readFileSync(new URL('../src/app.js',import.meta.url),'utf8');
assert.match(app,/url&&auto\?url:'\.\/icons\/vacuum.svg'/,'unloaded photo must not be an img src');
assert.match(app,/event.stopPropagation\(\)/,'photo button must not open device card');
assert.match(app,/data-load-photo/);
assert.match(app,/function partPhoto/);
assert.doesNotMatch(app,/part\.imageUrl\?`<div class="part-photo/,'part images must use shared policy');
console.log('Photo checks passed: default list, detail, explicit loading, invalid preference and shared parts policy.');
